"""
Report generation: Markdown, JSON, and CSV formats.

Design
------
* Reporters are pure functions that accept domain objects and return strings
  or write files.
* No secrets appear in any report.
* Illustrative vs. measured values are always distinguished.
* Report file names include experiment IDs and timestamps for traceability.
"""

from __future__ import annotations

import csv
import io
import logging
from datetime import UTC, datetime
from pathlib import Path

from llm_eval_lab.schemas import (
    ComparisonReport,
    Experiment,
    RegressionDecision,
)

logger = logging.getLogger(__name__)


# ── Helpers ───────────────────────────────────────────────────────────────────


def _fmt(value: float | None, decimals: int = 4) -> str:
    if value is None:
        return "N/A"
    return f"{value:.{decimals}f}"


def _decision_emoji(decision: RegressionDecision) -> str:
    return {
        RegressionDecision.IMPROVED: "✅ IMPROVED",
        RegressionDecision.REGRESSED: "❌ REGRESSED",
        RegressionDecision.INCONCLUSIVE: "⚠️  INCONCLUSIVE",
        RegressionDecision.INSUFFICIENT_DATA: "ℹ️  INSUFFICIENT_DATA",
    }.get(decision, decision.value)


# ── Experiment reports ────────────────────────────────────────────────────────


def experiment_to_markdown(experiment: Experiment) -> str:
    """Render an experiment as a Markdown report."""
    cfg = experiment.config
    s = experiment.summary
    lines: list[str] = []

    lines += [
        f"# Experiment Report: {cfg.name}",
        "",
        f"**ID:** `{cfg.experiment_id}`  ",
        f"**Status:** {experiment.status.value}  ",
        f"**Provider:** {cfg.provider.name} / {cfg.provider.model or '(default)'}  ",
        f"**Dataset:** {cfg.dataset_path}  ",
        f"**Started:** {experiment.started_at.isoformat() if experiment.started_at else 'N/A'}  ",
        f"**Completed:** {experiment.completed_at.isoformat() if experiment.completed_at else 'N/A'}  ",
        f"**Prompt version:** {cfg.prompt.version} (hash `{cfg.prompt.content_hash}`)  ",
        "",
        "---",
        "",
        "## Summary",
        "",
        "| Metric | Value |",
        "|--------|-------|",
        f"| Total cases | {s.total_cases} |",
        f"| Successful | {s.successful_cases} |",
        f"| Failed | {s.failed_cases} |",
        f"| Success rate | {_fmt(s.success_rate * 100, 1)}% |",
        f"| Mean latency | {_fmt(s.mean_latency_ms, 1)} ms |",
        f"| Median latency | {_fmt(s.median_latency_ms, 1)} ms |",
        f"| P90 latency | {_fmt(s.p90_latency_ms, 1)} ms |",
        f"| P95 latency | {_fmt(s.p95_latency_ms, 1)} ms |",
        f"| Prompt tokens | {s.total_prompt_tokens or 'N/A'} |",
        f"| Completion tokens | {s.total_completion_tokens or 'N/A'} |",
        f"| Estimated cost | {'$' + _fmt(s.estimated_cost_usd, 6) if s.estimated_cost_usd is not None else 'N/A (pricing not configured)'} |",
        "",
    ]

    if s.aggregate_metrics:
        lines += [
            "## Aggregate Metric Scores",
            "",
            "| Metric | Mean Score |",
            "|--------|------------|",
        ]
        for metric_name, score in sorted(s.aggregate_metrics.items()):
            lines.append(f"| {metric_name} | {_fmt(score)} |")
        lines.append("")

    if experiment.error:
        lines += ["## Error", "", "```", experiment.error, "```", ""]

    # Per-case results table
    if experiment.results:
        lines += [
            "## Per-Case Results",
            "",
            "| Case ID | Status | Output (truncated) | "
            + " | ".join(sorted({m.metric_name for r in experiment.results for m in r.metrics}))
            + " |",
        ]
        metric_cols = sorted({m.metric_name for r in experiment.results for m in r.metrics})
        header_sep = (
            "|---------|--------|-------------------|"
            + "|".join(["--------"] * len(metric_cols))
            + "|"
        )
        lines.append(header_sep)

        for r in experiment.results:
            status = "✅" if r.error is None else "❌"
            output = (r.output or r.error or "")[:60].replace("|", "\\|").replace("\n", " ")
            metric_vals = []
            for col in metric_cols:
                m = r.get_metric(col)
                metric_vals.append(_fmt(m.score) if (m and m.score is not None) else "N/A")
            lines.append(f"| {r.case_id} | {status} | {output} | " + " | ".join(metric_vals) + " |")
        lines.append("")

    lines += [
        "---",
        f"*Generated by LLM Evaluation Lab at {datetime.now(UTC).isoformat()}*",
        "*All outputs marked `is_simulated=True` were produced by the offline mock provider.*",
    ]

    return "\n".join(lines)


def experiment_to_json(experiment: Experiment) -> str:
    """Render an experiment as a JSON string."""
    return experiment.model_dump_json(indent=2)


def experiment_to_csv(experiment: Experiment) -> str:
    """Render per-case results as CSV."""
    if not experiment.results:
        return "case_id,status,output,error\n"

    metric_cols = sorted({m.metric_name for r in experiment.results for m in r.metrics})
    fieldnames = [
        "case_id",
        "input",
        "reference",
        "output",
        "status",
        "error",
        "latency_ms",
    ] + metric_cols

    buf = io.StringIO()
    writer = csv.DictWriter(buf, fieldnames=fieldnames)
    writer.writeheader()

    for r in experiment.results:
        row: dict = {
            "case_id": r.case_id,
            "input": r.input,
            "reference": r.reference or "",
            "output": r.output or "",
            "status": "failed" if r.error else "success",
            "error": r.error or "",
            "latency_ms": r.latency_ms or "",
        }
        for col in metric_cols:
            m = r.get_metric(col)
            row[col] = m.score if (m and m.score is not None) else ""
        writer.writerow(row)

    return buf.getvalue()


# ── Comparison reports ────────────────────────────────────────────────────────


def comparison_to_markdown(report: ComparisonReport) -> str:
    """Render a comparison report as Markdown."""
    lines: list[str] = [
        "# Comparison Report",
        "",
        f"**Comparison ID:** `{report.comparison_id}`  ",
        f"**Baseline:** `{report.baseline_id}`  ",
        f"**Candidate:** `{report.candidate_id}`  ",
        f"**Created:** {report.created_at.isoformat()}  ",
        f"**Bootstrap resamples:** {report.bootstrap_n}  ",
        f"**Confidence level:** {report.confidence_level * 100:.0f}%  ",
        f"**Seed:** {report.bootstrap_seed}  ",
        "",
        f"## Overall Decision: {_decision_emoji(report.overall_decision)}",
        "",
        "> **Note:** IMPROVED/REGRESSED means the bootstrap confidence interval "
        "for the metric difference lies entirely above/below the practical significance "
        "threshold. INCONCLUSIVE means the CI crosses zero or the threshold. "
        "INSUFFICIENT_DATA means there are too few paired samples.",
        "",
        "---",
        "",
        "## Per-Metric Comparison",
        "",
        "| Metric | Baseline | Candidate | Δ (abs) | Δ% | CI Lower | CI Upper | Decision | n |",
        "|--------|----------|-----------|---------|-----|----------|----------|----------|---|",
    ]

    for mc in report.metric_comparisons:
        ci_lo = _fmt(mc.ci.lower) if mc.ci else "N/A"
        ci_hi = _fmt(mc.ci.upper) if mc.ci else "N/A"
        lines.append(
            f"| {mc.metric_name} | {_fmt(mc.baseline_mean)} | {_fmt(mc.candidate_mean)} "
            f"| {_fmt(mc.absolute_change)} | {_fmt(mc.relative_change_pct, 1)}% "
            f"| {ci_lo} | {ci_hi} | {_decision_emoji(mc.decision)} | {mc.n_paired} |"
        )

    lines += [
        "",
        "## Metric Notes",
        "",
    ]
    for mc in report.metric_comparisons:
        if mc.notes:
            lines.append(f"**{mc.metric_name}:**")
            for note in mc.notes:
                lines.append(f"- {note}")
            lines.append("")

    if report.cases_improved:
        lines += [f"## Cases Improved ({len(report.cases_improved)})", ""]
        for cid in report.cases_improved[:20]:
            lines.append(f"- `{cid}`")
        if len(report.cases_improved) > 20:
            lines.append(f"- *(and {len(report.cases_improved) - 20} more)*")
        lines.append("")

    if report.cases_regressed:
        lines += [f"## Cases Regressed ({len(report.cases_regressed)})", ""]
        for cid in report.cases_regressed[:20]:
            lines.append(f"- `{cid}`")
        if len(report.cases_regressed) > 20:
            lines.append(f"- *(and {len(report.cases_regressed) - 20} more)*")
        lines.append("")

    lines += [
        "---",
        "## Statistical Caveats",
        "",
        "- Bootstrap CIs are approximate, especially for small samples (n < 30).",
        "- A CI that does not cross zero does not guarantee practical importance.",
        "- Multiple metric comparisons increase the risk of a false positive.",
        "- Judge-based metrics are subjective and should not be treated as ground truth.",
        "",
        f"*Generated by LLM Evaluation Lab at {datetime.now(UTC).isoformat()}*",
    ]

    return "\n".join(lines)


def comparison_to_json(report: ComparisonReport) -> str:
    return report.model_dump_json(indent=2)


# ── File I/O helpers ──────────────────────────────────────────────────────────


def save_report(content: str, path: Path) -> None:
    """Write report content to a file, creating parent directories as needed."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    logger.info("Report saved to %s", path)
